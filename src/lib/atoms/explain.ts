/** הדוגמאות של חלק או מנוע לפי מזהה; לא-מוכר ⇒ רשימה ריקה. */
export function examplesOf(id: string): readonly string[] {
  if (Object.prototype.hasOwnProperty.call(ATOM_EXPLAIN, id)) return ATOM_EXPLAIN[id as AtomId].examples;
  if (Object.prototype.hasOwnProperty.call(ENGINE_EXPLAIN, id)) return ENGINE_EXPLAIN[id as EngineId].examples;
  return [];
}
