/** רצ'ט — סכום בשקלים במילים (קבלת סעיף 46). ערכים נפוצים חייבים להיות תקינים. */
import { describe, expect, it } from 'vitest';
import { integerInWords, amountInWords } from '../hebrewNumber';

describe('integerInWords', () => {
  const cases: [number, string][] = [
    [0, 'אפס'],
    [1, 'אחד'],
    [5, 'חמישה'],
    [10, 'עשרה'],
    [11, 'אחד עשר'],
    [15, 'חמישה עשר'],
    [18, 'שמונה עשר'],
    [20, 'עשרים'],
    [21, 'עשרים ואחד'],
    [100, 'מאה'],
    [105, 'מאה וחמישה'],
    [120, 'מאה ועשרים'],
    [123, 'מאה עשרים ושלושה'],
    [200, 'מאתיים'],
    [250, 'מאתיים וחמישים'],
    [360, 'שלוש מאות ושישים'],
    [1000, 'אלף'],
    [1800, 'אלף ושמונה מאות'],
    [2000, 'אלפיים'],
    [3600, 'שלושת אלפים ושש מאות'],
    [5000, 'חמשת אלפים'],
    [10000, 'עשרת אלפים'],
    // ratchet P1-א׳1 — הבאג: 11..999 אלף עגולים קיבלו ו׳ על "אלף" עצמו
    // ("שמונה עשר ואלף") כי thousandWords החזיר מערך שטוח ו-joinHeb הדביק
    // ו׳ למילה האחרונה. הגיע לקבלות סעיף 46. התיקון: איבר אחד "…אלף".
    [11000, 'אחד עשר אלף'],
    [18000, 'שמונה עשר אלף'],
    [21000, 'עשרים ואחד אלף'],
    [100000, 'מאה אלף'],
    [999000, 'תשע מאות תשעים ותשעה אלף'],
    [18500, 'שמונה עשר אלף וחמש מאות'],
    [999999, 'תשע מאות תשעים ותשעה אלף תשע מאות תשעים ותשעה'],
    // אותו דפוס במיליונים ("שמונה עשר ומיליון") — תוקן באותו commit
    [18000000, 'שמונה עשר מיליון'],
    [21000000, 'עשרים ואחד מיליון'],
    [3000000, 'שלושה מיליון'],
  ];
  for (const [n, expected] of cases) {
    it(`${n} → ${expected}`, () => expect(integerInWords(n)).toBe(expected));
  }
  it('מחוץ לטווח → null', () => {
    expect(integerInWords(-5)).toBeNull();
    expect(integerInWords(1.5)).toBeNull();
    expect(integerInWords(1e12)).toBeNull();
  });
});

describe('amountInWords (₪)', () => {
  it('שקל בודד', () => expect(amountInWords(1)).toBe('שקל אחד'));
  it('רבים', () => expect(amountInWords(18)).toBe('שמונה עשר שקלים'));
  it('מאות', () => expect(amountInWords(250)).toBe('מאתיים וחמישים שקלים'));
  it('אלפים', () => expect(amountInWords(1800)).toBe('אלף ושמונה מאות שקלים'));
  it('אגורות', () => expect(amountInWords(18.5)).toBe('שמונה עשר שקלים ו-חמישים אגורות'));
  // ratchet — האגורה נקבה: "עשרים וחמש" (לא "…וחמישה" צורת-זכר). היה קפוא שגוי.
  it('שקל אחד + אגורות (נקבה)', () => expect(amountInWords(1.25)).toBe('שקל אחד ו-עשרים וחמש אגורות'));
  it('אגורות נקבה — יחידות', () => expect(amountInWords(0.03)).toBe('אפס שקלים ו-שלוש אגורות'));
  it('אגורה בודדת — יחיד', () => expect(amountInWords(0.01)).toBe('אפס שקלים ו-אגורה אחת'));
  it('שתי אגורות — סמיכות', () => expect(amountInWords(0.02)).toBe('אפס שקלים ו-שתי אגורות'));
  it('22 אגורות — סמיכות בעשרות', () => expect(amountInWords(0.22)).toBe('אפס שקלים ו-עשרים ושתיים אגורות'));
  it('מאות שקלים + אגורות נקבה', () => expect(amountInWords(123.45)).toBe('מאה עשרים ושלושה שקלים ו-ארבעים וחמש אגורות'));
  it('דולר', () => expect(amountInWords(5, '$')).toBe('חמישה דולרים'));
  // סנט זכר — צורת-הזכר נשמרת (לא מושפע מתיקון האגורות)
  it('סנט זכר', () => expect(amountInWords(5.25, '$')).toBe('חמישה דולרים ו-עשרים וחמישה סנט'));
  it('אפס', () => expect(amountInWords(0)).toBe('אפס שקלים'));
  // 🐛 נחיל-9×9 (13.8): גלישת-עיגול-אגורות — שבר ≥.995 עיגל ל-100 אגורות
  // ("6 ומאה אגורות"). כעת נשיאה לשקל השלם.
  it('גלישת-אגורות: 5.995 ⇒ שישה שקלים (לא "…ומאה אגורות")', () => expect(amountInWords(5.995)).toBe('שישה שקלים'));
  it('גלישת-אגורות: 0.999 ⇒ שקל אחד', () => expect(amountInWords(0.999)).toBe('שקל אחד'));
  // 🐛 נחיל-עמוק (13.8): 2 בצורת-סמיכות "שני שקלים" (לא "שניים שקלים"); סנט/דולר זכר גם כן
  it('שני שקלים — סמיכות (לא "שניים")', () => expect(amountInWords(2)).toBe('שני שקלים'));
  it('שני דולרים — סמיכות', () => expect(amountInWords(2, '$')).toBe('שני דולרים'));
  it('שני שקלים + אגורות', () => expect(amountInWords(2.5)).toBe('שני שקלים ו-חמישים אגורות'));
});

