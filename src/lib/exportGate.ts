/**
 * שער יציאת-מידע יחיד (13.8, בקשת-בעלים "כפתור שמבטל לעובד כל הוצאת מידע").
 * המנהל מכבה `core.export` בכרטיס-העובד ⇒ הקונפיג-האפקטיבי של אותה עובדת מסמן
 * את השער כחסום ⇒ כל נתיב הורדה/הדפסה/העתקה מסרב בנקודת-חנק אחת.
 *
 * למה נקודת-חנק ולא גידור פר-קריאה: `core.export` אינו חולק קידומת-נקודה עם
 * תת-דגלי-הייצוא (reports.csv / shop7.export / supporters.annualreport …) ולכן
 * `featureOn` לא משתרשר אליהם — גידור מפורש בכל אתר-הורדה דלף (~18 נתיבים).
 * במקום זאת פונקציות-ההורדה הבסיסיות עצמן שואלות את השער.
 *
 * חוזה-הדגלים נשמר: חסר=מותר, רק false חוסם. ברירת-המחדל כאן = מותר, כך שכל
 * הבדיקות והמשתמשים הרגילים אינם מושפעים עד שהמנהל חוסם עובדת במפורש.
 *
 * 🔒 22.10.2026 (נעילת-הדמו) — שתי שכבות, והחוזה מחוץ לדמו לא זז:
 *  • השער הקיים (guardExport/exportAllowed) — חסום = סשן-דמו **או** core.export=false. מחוץ לדמו
 *    התנאי וההודעה ביט-זהים; אותם נתיבים בדיוק עוברים בו כמו לפני הדמו.
 *  • מנעול-דמו נפרד (setDemoLocked/demoLocked/guardDemo) — לנתיבים שלא היו בשער לפני נעילת-הדמו:
 *    העתקות-ללוח (טלפוני-כיתה, שמות-לתפילה, סיכום/הדפסת כרטיס-הורה, מכתב-AI, הצעת-שימור,
 *    קישור-יומן), הקבצים-המצורפים בכרטיס-החוג (ExportLink) והגיבוי-המלא (store.exportBackup). נחסמים **רק
 *    בדמו** — עובד/ת שהמנהל חסם לה ייצוא רואה בהם בדיוק את מה שראתה קודם (ביקורת 22.10: החוזה
 *    המחמיר של core.export לא אושר ע"י הבעלים, ולכן לא הורחב).
 *  • עזרי-ההורדה/ההדפסה מחזירים בסירוב את refusalResult(): false **רק בדמו** ⇒ הקורא לא מציג אחרי
 *    הודעת-הדמו "…ירד/ה" כוזב. מחוץ לדמו true ⇒ הקורא ממשיך בדיוק כמו קודם (ביט-זהה, גם אצל עובד/ת
 *    שהייצוא חסום לה — כולל הודעת-ההצלחה שאחרי הסירוב וניסיון הקובץ השני בחבילת-האשף; שינוי שלהם
 *    מחוץ לדמו = הכרעת-בעלים, לא חלק מנעילת-הדמו).
 *    רישום-הגישה של דוח-המשפחה (logAccess) נשאר לפני ההורדה — גם ניסיון שנחסם נרשם, כמו קודם.
 */

let blocked = false;
let demo = false;
let notify: (() => void) | null = null;

/** נקבע מ-App לפי הקונפיג-האפקטיבי; onBlocked (אופציונלי) מריץ toast בסירוב. */
export function setExportBlocked(isBlocked: boolean, onBlocked?: () => void): void {
  blocked = isBlocked;
  notify = onBlocked ?? null;
}

/** האם יציאת-מידע מותרת כרגע (חסר-דגל/ברירת-מחדל ⇒ true). */
export function exportAllowed(): boolean {
  return !blocked;
}

/**
 * שער לפני כל נתיב-יציאה: מחזיר true אם מותר. אם חסום — מריץ את ההתרעה
 * (toast) ומחזיר false, כדי שהקורא יעצור בלי להוריד/להדפיס דבר.
 */
export function guardExport(): boolean {
  if (blocked) {
    notify?.();
    return false;
  }
  return true;
}

/**
 * 🔒 מנעול-הדמו (22.10.2026) — נקבע מ-App ליד setExportBlocked (isDemoSession). מחוץ לדמו false
 * תמיד ⇒ guardDemo מתיר ו-demoLocked שקר ⇒ הנתיבים שמשתמשים בהם ביט-זהים (גם אצל עובד/ת שהייצוא
 * חסום לה — core.export לא משפיע כאן).
 */
export function setDemoLocked(locked: boolean): void {
  demo = locked;
}

/**
 * מה עזר-הורדה/הדפסה מחזיר אחרי שהשער (guardExport) סירב: false רק בדמו — הקורא עוצר את
 * טוסט-ההצלחה; מחוץ לדמו true — הקורא ממשיך כמו לפני נעילת-הדמו (ביט-זהה). ראו למעלה.
 */
export function refusalResult(): boolean {
  return !demo;
}

/** האם זה סשן-דמו נעול (ExportLink: בלי href לקובץ-השמור). */
export function demoLocked(): boolean {
  return demo;
}

/**
 * שער לנתיבים שנחסמים **רק בדמו** (העתקה/הדפסה שלא עברו ב-guardExport לפני נעילת-הדמו):
 * בדמו — מריץ את ההתרעה (הודעת-הדמו, שנקבעה ב-setExportBlocked) ומחזיר false; אחרת true.
 */
export function guardDemo(): boolean {
  if (demo) {
    notify?.();
    return false;
  }
  return true;
}
