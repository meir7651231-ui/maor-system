/** התיבה: מזהה-העסק שהפלטה ביקשה ('' = אין) + צלצול שהמסך הפתוח תולה (ומסיר ביציאה). */
export const prOpenBox: { id: string; ring?: () => void } = { id: '' };

/** הפלטה: בקשה לפתוח עסק במדריך (לפני go('parnasa')) — מסך פתוח מקבל מיד, מסך שעולה — בעלייה. */
export function requestOpenListing(id: string): void {
  prOpenBox.id = id;
  prOpenBox.ring?.();
}
