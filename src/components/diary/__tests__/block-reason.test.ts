/**
 * ratchet — חסימת יומן החדרים לצום תשעה באב נדחה (ANALYSIS §5 בינוני #21).
 *
 * הבאג: `diary/lib.ts blockReason` חסם חגים מלאים לפי התאריך העברי המדויק, אבל
 * כשט' באב חל בשבת הצום נדחה לי' באב (ראשון) — וי' באב לא נחסם ביומן. הלוח
 * (`calendar/calLib.ts`) כבר החזיק את הדין; היומן היה חסר אותו. התיקון ממרכז את
 * אותו כלל: dow===0 ‏(ראשון) ‏+ י' באב ⇒ "תשעה באב (נדחה)".
 *
 * התאריכים אומתו מול חישוב הלוח העברי של המערכת עצמה (hebParts).
 */
import { describe, expect, it } from 'vitest';
import { blockReason } from '../lib';

const at = (iso: string) => blockReason(new Date(iso + 'T12:00:00'));

describe('🕯️ ratchet — תשעה באב נדחה ביומן החדרים', () => {
  it('י\' באב בראשון (ט\' באב חל בשבת) נחסם כצום נדחה — 7.8.2022', () => {
    // לפני התיקון: null (י' באב אינו חג מלא ואינו חוה"מ) ⇒ היום נראה פנוי לשיבוץ.
    expect(at('2022-08-07')).toBe('תשעה באב (נדחה)');
  });

  it('ט\' באב עצמו בשבת נשאר "שבת" (נחסם ממילא) — 6.8.2022', () => {
    expect(at('2022-08-06')).toBe('שבת');
  });

  it('ט\' באב ביום חול נחסם כ"תשעה באב" (בלי דחייה) — 13.8.2024 (שלישי)', () => {
    expect(at('2024-08-13')).toBe('תשעה באב');
  });

  it('אין דחייה שגויה: י\' באב ביום חול (ט\' באב לא בשבת) אינו נחסם — 14.8.2024 (רביעי)', () => {
    expect(at('2024-08-14')).toBeNull();
  });

  it('אין דחייה שגויה: ט\' באב בראשון (עצמו הצום) נחסם כ"תשעה באב", לא "נדחה" — 3.8.2025', () => {
    expect(at('2025-08-03')).toBe('תשעה באב');
  });
});
