    customer_name: str = ""
    invoices: tuple[OpenInvoice, ...] = ()
    payment_link: str = ""
    channel: str = "sms"              # "sms" | "email"
    state: State = State.IDLE
    offered_plan: tuple[Installment, ...] = ()
    bot_turns: int = 0                # כמה תשובות שלנו כבר היו בשיחה הזו
    policy: OwnerPolicy = field(default_factory=OwnerPolicy)
    manual_old: bool = False          # ר-7: יש חשבונית פתוחה מעל 3 שנים ⇒ אין הצעת פריסה אוטומטית
    footer_len: int = 0               # אורך שורת ההסרה שתתווסף ב-SMS (נשמר מקום בתקציב 268)

    def fits_sms(self, body: str) -> bool:
        """הגוף (לפני שם העסק) + שם העסק + שורת ההסרה ≤ תקרת התשובה ב-SMS."""
        return self.channel != "sms" or \
            len(frame(body, self)) + self.footer_len <= compliance.SMS_REPLY_MAX

    @property
    def total_agorot(self) -> int:
        return sum(i.amount_agorot for i in self.invoices)

    @property
    def currency(self) -> str:
        return self.invoices[0].currency if self.invoices else "ILS"

    @property
    def mixed_currency(self) -> bool:
        """חשבוניות פתוחות במטבעות שונים ⇒ אין סה״כ אחד (שקל+דולר לא מחברים), ולכן גם אין הצעת
        פריסה אוטומטית — `service.open_debt` מחזיר 0 ולא רושם הסדר. כרטיס לבעל העסק במקום."""
        return len({i.currency for i in self.invoices}) > 1

    def total_text(self) -> str:
        """הסכום לתצוגה. מטבעות שונים ⇒ סכום לכל מטבע («₪1,000 + $200»), לא חיבור."""
        if not self.mixed_currency:
            return fmt_amount(self.total_agorot, self.currency) if self.invoices else ""
        by: dict[str, int] = {}
        for i in self.invoices:
            by[i.currency] = by.get(i.currency, 0) + i.amount_agorot
        return " + ".join(fmt_amount(v, c) for c, v in by.items())

    @property
    def first_name(self) -> str:
        return (self.customer_name or "").split()[0] if self.customer_name.strip() else ""


