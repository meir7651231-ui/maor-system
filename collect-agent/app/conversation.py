_NIKUD = re.compile("[\u0591-\u05C7]")
_QUOTES = str.maketrans({"״": '"', "”": '"', "“": '"', "׳": "'", "’": "'", "‘": "'",
                         "`": "'", "–": "-", "—": "-", "\u200f": "", "\u200e": ""})
_FINALS = str.maketrans("ךםןףץ", "כמנפצ")


def normalize(text: str) -> str:
    t = _NIKUD.sub("", text or "").translate(_QUOTES).lower()
    t = t.replace("''", '"').translate(_FINALS)  # אותיות סופיות ⇒ רגילות (גם בתבניות)
    t = re.sub(r"(.)\1{2,}", r"\1\1", t)        # "תודההההה" ⇒ "תודהה"
    t = re.sub(r"\s+", " ", t)
    return t.strip()


@cache
def _c(pat: str) -> re.Pattern[str]:
    """קומפילציה של תבנית שרצה על טקסט מנורמל: גם בה אותיות סופיות ⇒ רגילות."""
    return re.compile(pat.translate(_FINALS))


def _s(pat: str, t: str) -> re.Match[str] | None:
    return _c(pat).search(t)


def _fm(pat: str, t: str) -> re.Match[str] | None:
    return _c(pat).fullmatch(t)


def _m(pat: str, t: str) -> re.Match[str] | None:
    return _c(pat).match(t)


# תחיליות עבריות נפוצות לפני מילה: ו/ש/כש/ה/ב/ל/מ וצירופים
_P = r"(?<![\w])(?:ו?(?:כש|ש|ה|ב|ל|מ){0,2})?"
_E = r"(?![\w])"


def _w(*words: str) -> str:
    """מילה שלמה עם תחיליות מותרות."""
    return _P + "(?:" + "|".join(words) + ")" + _E


def _ws(*stems: str) -> str:
    """שורש + כל סיומת (למשל שילמ ⇒ שילמתי/שילמנו/שילמה)."""
    return _P + "(?:" + "|".join(stems) + r")\w*"


_NEG_BEFORE = _c(r"(?:(?<![\w])(?:לא|טרם|עוד לא|עדיין לא|אף פעם לא|לא ממש|בלי ש|מבלי ש|אל|אין צורך|"
                 r"לא (?:צריך|צריכה|צריכים|ביקשתי|ביקשנו|מבקש|מבקשת|רוצה|התכוונתי)(?: ל)?|"
                         r"לא\s+\w+\s+ש)\s*$)")


def _hits(pattern: re.Pattern[str], t: str, *, negatable: bool = False) -> bool:
    for m in pattern.finditer(t):
        if negatable and _NEG_BEFORE.search(t[max(0, m.start() - 22):m.start()]):
            continue
        return True
    return False


# מנהל 250 (סריקת גבולות מילה): חלק שמתחיל באות עברית יכול היה להתחיל באמצע מילה —
# «די לשלוח» בתוך «כדי לשלוח» ⇒ הסרה לצמיתות של לקוח ששאל איך לשלם; «נזק» בתוך «טרנזקציה» ⇒ מחלוקת;
# «חולה» בתוך «כחולה» ⇒ השהיה. השער: תחילת ההתאמה = תחילת מילה, או אחרי תחילית עברית תקנית בלבד
# (ו/ש/כש/ה/ב/ל/מ, כמו _P). lookbehind בלבד ⇒ נקודת ההתחלה לא זזה ובדיקת השלילה (_NEG_BEFORE) לא משתנה.
_HEB_START = re.compile(r"^(?:\(\?:|\(|\^)*[\u05D0-\u05EA]")


def _lead_variants() -> list[str]:
    units = ("כש", "ש", "ה", "ב", "ל", "מ")
    out = {""}
    for a in ("", "ו"):
        out.add(a)
        for u1 in units:
            out.add(a + u1)
            for u2 in units:
                out.add(a + u1 + u2)
    return sorted(v.translate(_FINALS) for v in out if v)


def _word_start_guard() -> str:
    by_len: dict[int, list[str]] = {}
    for v in _lead_variants():
        by_len.setdefault(len(v), []).append(v)
    alts = [r"(?<![\u05D0-\u05EA])"]
    for n in sorted(by_len):
        alts.append(r"(?<=(?<![\u05D0-\u05EA])(?:" + "|".join(by_len[n]) + "))")
    return "(?:" + "|".join(alts) + ")"


_WSG = _word_start_guard()


def _guard(part: str) -> str:
    return _WSG + "(?:" + part + ")" if _HEB_START.match(part) else part


def _rx(*parts: str) -> re.Pattern[str]:
    return _c("|".join(_guard(p) for p in parts))


