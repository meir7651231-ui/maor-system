def detect(text: str, ctx: Context | None = None) -> list[Intent]:
    """כל הכוונות שזוהו, לפי סדר העדיפות."""
    t = normalize(text)
    if not t:
        return [Intent.UNKNOWN]
    found: set[Intent] = set()
    for it, rx in RX.items():
        if it in STATEFUL:
            continue
        if _hits(rx, t, negatable=it in NEGATABLE):
            found.add(it)
    awaiting = ctx is not None and ctx.state == State.AWAITING_PLAN_REPLY
    if awaiting:
        if _hits(RX[Intent.PLAN_REJECT], t):
            found.add(Intent.PLAN_REJECT)
        elif _hits(RX[Intent.PLAN_ACCEPT], t):
            found.add(Intent.PLAN_ACCEPT)
        # ספרה לבד או "ב-4" ⇒ הצעה נגדית
        if _fm(r"\W*(?:אפשר |ו?אם |מה עם )?(?:ב-?|ל-?)?(\d{1,2}|" + _NUMW + r")\W*\??", t) or \
                _s(r"(?:אפשר|ואם|מה עם|רק|אולי) (?:ב-?|ל-?)?(\d{1,2}|" + _NUMW + r")(?![\d\w])", t):
            found.add(Intent.PLAN_REQUEST)
    # זיהוי לפי שם הלקוח מההקשר: "אין פה דנה" / "אני לא דנה" / "לא מכיר שום דנה"
    fn = normalize(ctx.first_name) if ctx is not None else ""
    if fn and len(fn) >= 2 and _s(r"(?:אין (?:פה|כאן|בבית|בטלפון הזה)|לא מכיר\w*|אני לא|זה לא|מי (?:זאת|זה|זו)|אין לי)"
                                  r"\W+(?:\w+\W+){0,2}" + re.escape(fn) + r"(?![\w])", t):
        found.add(Intent.WRONG_PERSON)
    if fn and len(fn) >= 2 and _s(r"(?<![\w])לא\W+" + re.escape(fn) + r"\W+(?:פה|כאן|בבית|גר|גרה)(?![\w])", t):
        found.add(Intent.WRONG_PERSON)
    # שאלה על תשלום ("מתי שילמתי?") ≠ טענת תשלום
    if Intent.PAID_CLAIM in found and _s(r"^\W*(?:מתי|האם|כמה|למה|איך|מה)\b[^.!]*\?\W*$", t) \
            and not _s(r"(?:כבר )?(?:שילמתי|העברתי|שילמנו|העברנו)[^?]*[.!,]", t):
        found.discard(Intent.PAID_CLAIM)
    # הבטחה בזמן הווה עם תאריך: "תוך שבוע אני מסדר"
    # מנהל 248 (qa6 x6-41): «רק עכשיו ראיתי. איך משלמים?» — הפועל בתוך שאלת «איך/לאן» אינו הבטחה
    _t_noq = re.sub(_c(r"(?:איך|לאן|למי|איפה|כמה|באיזה \w+|באיזו \w+)\s+(?:\w+\s+){0,2}?(?:משלמ|מעביר|מפקיד|מסדר)\w*"), " ", t)
    if ctx is not None and Intent.PROMISE not in found and \
            _hits(_c(_ws("מסדר", "מעביר", "משלמ", "מטפל", "מפקיד", "סוגר")), _t_noq, negatable=True) and \
            (extract_date(t, ctx.today)[0] or _s(r"(?:עכשיו|כרגע|מיד|תיכף|בדקות הקרובות)", t)):
        found.add(Intent.PROMISE)
    if ctx is not None and ctx.state == State.AWAITING_DATE:
        d, _vague = extract_date(t, ctx.today)
        if d is not None:
            found.add(Intent.PROMISE)
    # מנהל 242 (self4): «לא מכיר את המספר הזה, זה ממי?» = שאלה על השולח, לא «טעות במספר». בלי שם/«אין פה»/«טעות»
    # ⇒ who_is_this (תשובה עם שם העסק). רצפת ההגנה ב-respond עדיין משהה ומעלה כרטיס, כי wrong_person נתפס גולמית.
    if Intent.WRONG_PERSON in found and Intent.WHO_IS_THIS in found and \
            _s(r"לא (?:מכיר|מכירה|מזהה|מזהים|מכירים) (?:את )?(?:ה)?(?:מספר|שולח|טלפון)", t) and \
            not _s(r"טעות|בטעות|אין (?:פה|כאן)|זה לא אני|לא (?:ה)?לקוח|לא שלי|החלפתי|לא שייך", t) and \
            not (fn and len(fn) >= 2 and _s(re.escape(fn), t)):
        found.discard(Intent.WRONG_PERSON)
    # תיקוני התנגשות ידועים
    if Intent.PAID_CLAIM in found and _s(r"(?:איך|לאן|למי) (?:אפשר )?(?:לשלם|להעביר)", t) \
            and not _s(r"שילמתי|העברתי", t):
        found.discard(Intent.PAID_CLAIM)
    if Intent.CANT_PAY in found and _s(r"אין (?:לי|לנו) בעיה", t):
        found.discard(Intent.CANT_PAY)
    # "לא שלי" עם טענה נגד החוב, בלי סימני מספר/כתובת שגויים ⇒ מחלוקת (שומרת את החוב ומסלימה בדחיפות)
    if Intent.WRONG_PERSON in found and Intent.DISPUTE in found and not _s(
            r"מספר|מס'|כתובת|מייל|בטעות|לא מכיר|לא מכירה|אין (?:פה|כאן)|טלפון", t):
        found.discard(Intent.WRONG_PERSON)
    # ספק/שאלה על תשלום ("לא זוכר אם שילמתי", "האם התשלום התקבל?") ≠ טענת תשלום
    if Intent.PAID_CLAIM in found and (
            _s(r"(?:לא זוכר\w*|לא בטוח\w*|לבדוק|לברר|לוודא) (?:אם|האם|ש)", t)
            or _s(r"(?<![\w])(?:אם|האם) (?:כבר )?(?:שילמ|העבר|התשלום|הכסף)", t)) \
            and not _s(r"(?:^|[.!,\n] *)(?:כבר )?(?:שילמתי|שילמנו|העברתי|העברנו)(?![^.!?\n]*\?)", t):
        found.discard(Intent.PAID_CLAIM)
    # מנהל 249 (qa7 x7-42/45): «I haven't paid yet» / «not sure if I paid» ≠ טענת תשלום (אחרת: «תודה שעדכנתם» + השהיה)
    if Intent.PAID_CLAIM in found:
        t_en = re.sub(r"\b(?:have\s*n'?t|have\s+not|has\s*n'?t|has\s+not|had\s*n'?t|did\s*n'?t|did\s+not|not|never|"
                      r"if\s+(?:i|we)(?:'ve|\s+have|\s+already)?|whether\s+(?:i|we)(?:'ve|\s+have|\s+already)?|"
                      r"did\s+(?:i|we)|have\s+(?:i|we))\s+(?:yet\s+|already\s+|actually\s+)?(?:been\s+)?paid\b(?:\s+yet)?", " ", t)
        if t_en != t and not _hits(RX[Intent.PAID_CLAIM], t_en):
            found.discard(Intent.PAID_CLAIM)
    if not found and "?" in t and _s(r"(?:ה)?(?:קישור|לינק)", t):
        found.add(Intent.HOW_TO_PAY)          # שאלה על הקישור לתשלום
    if not found and "?" not in t and _s(r"(?<![\w])(?:תודה|thanks)", t):
        found.add(Intent.THANKS)              # שבח + תודה בלי בקשה
    # "התשלום/ההעברה לא בוצע/ה" = תקלה בתשלום: לא טענה נגד החוב (critic סבב 80 🟡) וגם לא "שילמתי" ⇒ how_to_pay
    _failed_pay = r"(?:ה)?(?:תשלום|העברה|הפקדה|ביט|פייבוקס)\W+(?:\w+\W+){0,2}לא (?:בוצע|בוצעה|עבר|עברה|הצליח|הצליחה|נקלט|נקלטה)"
    # critic סבב 81: טענת תשלום מפורשת (גם כשאחריה «לא עבר») ⇒ נשאר paid_claim — אחרת ממשיכים לתזכר ושולחים קישור
    # למי שהכסף ירד לו (חשש לתשלום כפול). רק תקלה בלי טענה ⇒ how_to_pay
    _claims_paid = (r"(?<![\w])(?:כבר )?(?:שילמתי|שילמנו|העברתי|העברנו|הפקדתי|חויבתי|חויבנו)(?![\w])"
                    r"|ירד (?:לי |לנו )?(?:ה?כסף |הסכום )?מ?ה?(?:חשבון|כרטיס|אשראי)|(?:הכסף|הסכום) ירד")
    if Intent.PAID_CLAIM in found and _s(_failed_pay, t) and not _s(_claims_paid, t):
        found.discard(Intent.PAID_CLAIM)
        found.add(Intent.HOW_TO_PAY)
    if Intent.DISPUTE in found and _s(r"(?:ה)?(?:תשלום|העברה|הפקדה|ביט|פייבוקס)\W+(?:\w+\W+){0,2}לא (?:בוצע|בוצעה|עבר|עברה|הצליח|הצליחה|נקלט|נקלטה)", t) \
            and not _s(_KEEPS_DISPUTE, t):
        found.discard(Intent.DISPUTE)
        found.add(Intent.HOW_TO_PAY)
    # "הלינק לא עובד" = בעיה טכנית בקישור, לא מחלוקת על החוב
    if Intent.DISPUTE in found and _s(r"(?:קישור|לינק)\W+(?:\w+\W+){0,2}(?:לא )(?:עובד|נפתח|נטען)", t) \
            and not _s(_KEEPS_DISPUTE + r"|לא אשלם", t):  # critic סבב 79
        found.discard(Intent.DISPUTE)
        found.add(Intent.HOW_TO_PAY)
    # "זה לא אני ש… אבל אשלם" ⇒ מכיר בחוב: לא מספר שגוי (אחרת מסירים ומוחקים טלפון למשלם)
    if Intent.WRONG_PERSON in found and _s(_ws("אשלם", "נשלם", "אעביר", "נעביר", "אסדר", "נסדר", "אסדיר"), t) \
            and not _s(r"מספר|טלפון|בטעות|לא מכיר|רק אם|תוכיח|הוכח|לא אשלם", t):  # critic סבב 79: התניה ≠ הכרה
        found.discard(Intent.WRONG_PERSON)
    # עו"ד שממליץ לשלם / "דיברתי עם עו"ד" + כוונת תשלום, בלי מילות הליך ⇒ לא איום
    if Intent.LEGAL in found and (Intent.HOW_TO_PAY in found or Intent.PROMISE in found or _s(
            r"(?:אמר|אמרה|אמרו|המליץ|המליצה)\w* (?:לי )?(?:ש)?(?:כדאי )?(?:לי )?(?:פשוט )?לשלם", t)) \
            and not _s(_KEEPS_LEGAL, t):  # critic סבב 79: ייצוג ⇒ נשאר legal (לא פונים ישירות למיוצג)
        found.discard(Intent.LEGAL)
    # critic סבב 79: «don't remove me / no need to remove» ⇒ לא הסרה (כמו «לא צריך להסיר» בעברית) — רק אם אין הסרה אחרת
    if Intent.OPT_OUT in found:
        t2 = re.sub(r"\b(?:please )?(?:don'?t|do not|no need to|you don'?t need to)\s+(?:remove|unsubscribe|take)\b[^.!?,]*",
                    " ", t, flags=re.I)
        if t2 != t and not _hits(RX[Intent.OPT_OUT], t2):
            found.discard(Intent.OPT_OUT)
    # "הנכד בן 16 ישלם בשבילי" — הקטין משלם עבור המבוגר, לא עונה במקומו (qa3) ⇒ לא קטין
    if Intent.MINOR in found and _s(r"(?:ישלם|תשלם|יעביר|תעביר|יסדר|תסדר)\w*\s+(?:\w+\s+){0,2}(?:בשבילי|עבורי|במקומי|לכם)", t) \
            and not _s(r"ענה|ענתה|קיבל|קיבלה|ראה|ראתה|הטלפון של|המספר של|המכשיר של|אל תכתבו|תפסיקו|אני (?:בן|בת|קטין)", t):
        found.discard(Intent.MINOR)
    # סבב 10: "אל תשלחו מיילים, רק הודעה לנייד" = העדפת ערוץ, לא הסרה — אם אין מילת-תמידיות ויש ערוץ חלופי מבוקש.
    # (עם "יותר/שוב/אף פעם/שום" ⇒ נשאר הסרה, לפי critic סבב 89: הסרה מכובדת + כרטיס.)
    if Intent.OPT_OUT in found and _s(r"(?:^|\W)רק\s+(?:ב|ל|דרך\s+)?(?:מייל|אימייל|סמס|SMS|מסרונ|הודעה|נייד|טלפון|הודעת טקסט)", t) \
            and not _s(r"יותר|שוב|אף פעם|בכלל|לעולם|שום|מהרשימה|תסירו|הסירו|להסיר|הסר(?![\w])|stop"
                       r"|סטופ|עצור|עצרו|תעצרו", t):  # critic סבב 91: מילת הסרה מפורשת ⇒ נשאר הסרה
        found.discard(Intent.OPT_OUT)
    # "טעות בשם/בכתובת… אבל לא נורא/זה בסדר, אשלם" ⇒ לא מחלוקת (self4)
    if Intent.DISPUTE in found and _s(r"טעות (?:קטנה )?ב(?:שם|כתובת|איות|תאריך)", t) \
            and _s(r"(?:אבל|אך)\s+(?:זה |לא )?(?:בסדר|נורא|משנה|חשוב)|אשלם|אעביר|נשלם", t) and not _s(_KEEPS_DISPUTE, t):
        found.discard(Intent.DISPUTE)
    # "stop calling me sir/madam" = כינוי, לא בקשת הפסקת פנייה (self4)
    if Intent.OPT_OUT in found and _s(r"\bstop calling me (?:sir|madam|ma'?am|mr|mrs|ms|bro|dude|that|names|by)\b", t):
        found.discard(Intent.OPT_OUT)
    # בקשת קבלה / "send me the invoice again" ⇒ copy_request (הענף מבדיל קבלה מהעתק חשבונית)
    if not (found - {Intent.UNKNOWN, Intent.THANKS}) and (_s(_RECEIPT, t) or _s(r"\b(?:re)?send\b.{0,20}\binvoice\b", t)):
        found.discard(Intent.UNKNOWN)
        found.add(Intent.COPY_REQUEST)
    # שאלה על עו"ד ("אתם עובדים עם עו"ד?") ≠ איום
    if Intent.LEGAL in found and "?" in t and _s(r"(?:אתם|יש לכם|האם)\W+(?:\w+\W+){0,3}(?:עו\"ד|עורכ\w* ה?דין)", t) \
            and not _s(_KEEPS_LEGAL, t):  # critic סבב 80
        found.discard(Intent.LEGAL)
    # "אם לא אשלם…?" = שאלה על השלכות, לא סירוב
    if Intent.DISPUTE in found and _s(r"(?:^|\W)(?:ו?אם|מה קורה אם|מה יקרה אם)\s+לא\s+(?:אשלם|נשלם|אעביר)", t) \
            and not _s(_KEEPS_DISPUTE, t):  # critic סבב 80
        found.discard(Intent.DISPUTE)
    # critic סבב 108: «אם הביטוח ישלם…» = תנאי, לא הבטחה (בעל העסק צריך לדעת שהתשלום תלוי בצד שלישי)
    if Intent.PROMISE in found and _s(r"(?:^|\W)(?:רק\s+)?אם\s+(?:ה)?(?:ביטוח|חברת\s+ה?ביטוח)", t) and not _s(
            r"(?<![\w])(?:אשלם|נשלם|אעביר|נעביר)(?![\w])", t):
        found.discard(Intent.PROMISE)
    # "אני עורכת דין" (זהות, לא איום) ⇒ לא legal, אלא אם יש גם מילת הליך
    if Intent.LEGAL in found and _s(r"אני (?:עורכ\w*|עו\"ד)(?: דין)?(?: בעצמי| במקצוע)?", t) and not _s(
            _KEEPS_LEGAL + r"|שלי (?:י|ת)", t):
        found.discard(Intent.LEGAL)
    # "שלחו לינק ואשלם" — בלי תאריך, הדבר המועיל הוא הקישור
    if Intent.PROMISE in found and Intent.HOW_TO_PAY in found and ctx is not None \
            and extract_date(t, ctx.today)[0] is None:
        found.discard(Intent.PROMISE)
    # מנהל 248: חשש מהונאה גובר על «איך משלמים/הקישור» — לא דוחפים קישור למי שחושש לפתוח אותו
    if Intent.WHO_IS_THIS in found and _s(_PHISH, t):
        found.discard(Intent.HOW_TO_PAY)
        found.discard(Intent.UNKNOWN)
    if Intent.THANKS in found and len(found) > 1:
        found.discard(Intent.THANKS)
    if Intent.PLAN_ACCEPT in found and (found & {Intent.DISPUTE, Intent.OPT_OUT, Intent.LEGAL}):
        found.discard(Intent.PLAN_ACCEPT)
    if Intent.WRONG_PERSON in found and Intent.DISPUTE in found and \
            _s(r"טעות (?:ב)?(?:מספר|מס')|מספר (?:שגוי|לא נכון)", t):
        found.discard(Intent.DISPUTE)
    # "פיטרו... ואני מבקש תשלומים" — שני האותות נשמרים; הבטחה בלי תאריך מעל כוונת פריסה ⇒ פריסה עיקרית
    if not found:
        found.add(Intent.UNKNOWN)
    out = [i for i in PRIORITY if i in found]
    # סט משפט xl-29: «הייתי במילואים, מעביר השבוע» — המילואים הם הסבר לעיכוב, לא חוסר יכולת.
    # הבטחה עיקרית; CANT_PAY נשאר משני ⇒ תגית reservist + השהיה + כרטיס לבעל העסק נשמרים.
    if Intent.CANT_PAY in found and Intent.PROMISE in found and _s(_RESERVIST_PAST, t) and \
            not _hits(RX[Intent.CANT_PAY], re.sub(_RESERVIST_PAST, " ", t)):
        out.remove(Intent.PROMISE)
        out.insert(out.index(Intent.CANT_PAY), Intent.PROMISE)
    # סט משפט xl-12: «צו פתיחת הליכים בבית המשפט» — בית המשפט הוא של הליך חדלות הפירעון, לא תביעה נגדנו.
    # חוסר יכולת (חדלות) עיקרי; LEGAL נשאר משני ⇒ תגית legal + דחוף + השהיה נשמרים.
    if out[:2] == [Intent.LEGAL, Intent.CANT_PAY] and _s(_INSOLVENCY, t) and \
            not _hits(RX[Intent.LEGAL], re.sub(r"(?:ב|מ|ל)?בית (?:ה)?משפט|(?:ה)?נאמנ", " ", t)):
        out[0], out[1] = Intent.CANT_PAY, Intent.LEGAL
    return out


_INSOLVENCY = r"פשיטת רגל|חדלות פירעונ|צו כינוס|צו פתיחת הליכימ|הליכ חדלות|כונס נכסימ"
_RESERVIST_PAST = r"(?:הייתי|חזרתי|יצאתי|השתחררתי|שוחררתי)\s+(?:מ|ב)?(?:ה)?מילואי[םמ]"
# שאלה על העברת המידע לאחרים («מי עוד קיבל», «למי נתתם») ⇒ בעל העסק. «מאיפה יש לכם את המספר» לבד = זיהוי (d146)
_DATA_SOURCE = (r"מי עוד (?:קיבל|קיבלה|קיבלו|רואה|ראה|יודע)|למי (?:עוד )?(?:נתתם|העברתם|מסרתם|מכרתם)"
                r"|(?:נתתם|העברתם|מסרתם|מכרתם) (?:את )?(?:ה)?(?:פרטים|מספר|טלפון|מייל) (?:שלי )?ל")


