"""מנהל 284 · אותיות מתחפשות (homoglyphs) ותווי רוחב-מלא — טהור, בלי תלויות.

🔴 נכנס: «ЅТОР» / «STОP» (אותיות קיריליות/יווניות שנראות לטיניות — נפוץ בהעתק-הדבק ובמקלדות מעורבבות),
«ＳＴＯＰ» / «ｕｎｓｕｂｓｃｒｉｂｅ» (רוחב מלא), «𝐒𝐓𝐎𝐏» (מודגש מתמטי, «פונט מעוצב» ברשתות) ⇒ «לא ברור»:
**בקשת הסרה לא כובדה** (ברוחב מלא — אפילו בלי השהיה).
🔴 יוצא: «！！» / «‼» (רוחב מלא / סימן כפול), «ＵＲＧＥＮＴ», «ВDI» (B קירילית), «Ваnk Lеumi» — המעקה לא חסם.

`fold` — מתקפל **רק** תווים שאין להם שימוש לגיטימי בהודעת SMS עברית:
  • רוחב-מלא (U+FF01–FF5E), אלפאנומרי מתמטי (U+1D400–1D7FF), אותיות מוקפות (Ⓢ), אותיות עיליות (ˢᵗᵒᵖ),
    וסימני קריאה/שאלה כפולים (‼ ⁇ ⁈ ⁉ ﹗ ﹖) ⇒ NFKC.
  • מילה (רצף אותיות) **מעורבת** לטינית + קירילית/יוונית מתחפשת ⇒ כולה לטינית («STОP» ⇒ «STOP»).
  • מילה קירילית שיש בה אות **שאינה ברוסית** ומתחפשת ללטינית (Ѕ, Ј, і, ѕ, ԁ…) ⇒ לטינית («ЅТОР» ⇒ «STOP»).
  רוסית אמיתית («перестаньте», «стоп») **לא משתנה** — זיהוי השפה הזרה ממשיך לעבוד.
`skeleton` — כל אות מתחפשת ⇒ לטינית, בלי תנאי. רק לבדיקות שהן «רק מחמירות» (מעקה יוצא; הודעה שכולה מילת הסרה).
"""
from __future__ import annotations

import re
import unicodedata

# קירילית/יוונית שנראית כמו לטינית (רשימה שמרנית — רק צורות כמעט זהות)
_CONF = {
    # קירילית גדולות
    "А": "A", "В": "B", "Е": "E", "К": "K", "М": "M", "Н": "H", "О": "O", "Р": "P", "С": "C", "Т": "T",
    "Х": "X", "У": "Y", "Ѕ": "S", "І": "I", "Ј": "J", "Ԛ": "Q", "Ԝ": "W", "Ӏ": "I",
    # קירילית קטנות
    "а": "a", "е": "e", "о": "o", "р": "p", "с": "c", "у": "y", "х": "x", "ѕ": "s", "і": "i", "ј": "j",
    "ԁ": "d", "ԛ": "q", "ԝ": "w", "һ": "h", "ӏ": "l", "т": "t", "к": "k",
    # יוונית
    "Α": "A", "Β": "B", "Ε": "E", "Ζ": "Z", "Η": "H", "Ι": "I", "Κ": "K", "Μ": "M", "Ν": "N", "Ο": "O",
    "Ρ": "P", "Τ": "T", "Υ": "Y", "Χ": "X", "ο": "o", "ν": "v", "ι": "i", "κ": "k", "ρ": "p", "τ": "t",
}
# אותיות קיריליות שאינן באלפבית הרוסי — מילה שמכילה אותן ומתחפשת כולה היא כמעט תמיד הסוואה
_NON_RU = set("ЅІЈԚԜӀѕіјԁԛԝһӏ")
_CONF_TR = str.maketrans(_CONF)
_COMPAT = re.compile("[！-～\U0001d400-\U0001d7ffⒶ-ⓩʰ-ˤᴬ-ᵪ⁰-ₜ"
                     "‼⁇-⁉﹖﹗]")
_SUSPECT = re.compile("[！-～\U0001d400-\U0001d7ffⒶ-ⓩʰ-ˤᴬ-ᵪ⁰-ₜ"
                      "‼⁇-⁉﹖﹗\u0370-\u03ff\u0400-\u04ff\u0500-\u052f]")
_WORD = re.compile(r"[^\W\d_]+")
_LATIN = re.compile("[A-Za-z]")


def _compat(m: re.Match[str]) -> str:
    ch = m.group(0)
    out = unicodedata.normalize("NFKC", ch)
    # ספרות עיליות/תחתיות (¹ ₂) לא מתקפלות — «500¹» אינו 5001
    return ch if out.isdigit() else out


def _word(m: re.Match[str]) -> str:
    w = m.group(0)
    if not any(c in _CONF for c in w):
        return w
    if not all(c in _CONF or ("A" <= c <= "Z") or ("a" <= c <= "z") for c in w):
        return w          # מילה רוסית/יוונית אמיתית עם אותיות שאינן מתחפשות ⇒ לא נוגעים
    if _LATIN.search(w) or any(c in _NON_RU for c in w):
        return w.translate(_CONF_TR)
    return w


def fold(text: str) -> str:
    if not text or not _SUSPECT.search(text):
        return text
    return _WORD.sub(_word, _COMPAT.sub(_compat, text))


def skeleton(text: str) -> str:
    """כל המתחפשות ⇒ לטינית, בלי תנאי. רק לבדיקות מחמירות."""
    return fold(text).translate(_CONF_TR) if text else text
