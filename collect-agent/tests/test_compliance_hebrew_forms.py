"""מסנן הניסוח (ר-1) מול צורות עבריות אמיתיות — ביקורת גבי שיווק, 15.11 (המשך לבאג «עורך דין»).

שורש רוב הדליפות: דפוס שנכתב עם אות סופית («דחוף», «קופון», «הצטרפו») לא תופס נטייה שבה האות כבר לא
סופית («דחופה», «קופונים», «הצטרף»), ולהפך. ועוד חוסרי נטייה: כינויי קניין («חובך»), תחיליות («לבית הדין»),
יחיד/רבים («דמי פיגור», «ריביות», «הנחות»), ומילים נרדפות («פרקליט», «מעביד», «נעקל»).
התיקון רק **מחמיר** את החסימה; רשימת השליליות למטה נועלת שאין חיובי-שווא בניסוח רגיל של תזכורות.
"""
import pytest

from app import compliance

R = compliance.Rules(business="סטודיו נועה", allow_debt_word=False)

LEAKS = [
    ("lawyer", "נעביר לפרקליט"), ("lawyer", "הפרקליטה שלנו תפנה אליך"),
    ("seizure", "נעקל את החשבון"),
    ("fees", "יחויבו דמי פיגור"), ("fees", "דמי הפיגור יחולו"), ("fees", "ריביות על האיחור"),
    ("debt_word", "חובך עומד על 500"), ("debt_word", "חובכם"), ("debt_word", "חובו של הלקוח"),
    ("debt_word", "חובותיך"), ("debt_word", "בחובך"),
    ("court", "נעביר לבית הדין"), ("court", "נתבע אותך"), ("court", "לתבוע"),
    ("pressure", "זה דחופה"), ("pressure", "בקשה דחופה"),
    ("marketing", "קופונים לחברים"), ("marketing", "שירותים חדשים"), ("marketing", "הצטרף עכשיו"),
    ("discount", "הנחות לחג"),
    ("third_party", "נפנה למעביד שלך"), ("third_party", "נספר למשפחתך"),
]

CLEAN = [
    "שלום דני, חשבונית 1043 ע\"ס 1,800 ₪ טרם סומנה כשולמה.",
    "תודה! עצרנו את התזכורות ונבדוק את התשלום.",
    "אפשר גם בתשלומים, בלי תוספת.",
    "עורך הווידאו שלנו סיים את העבודה.",
    "לפי ההנחיות שקיבלנו.",
    "נשמח לעזור, אפשר להשיב כאן.",
    "החשבונית עדיין פתוחה. לתשלום בקישור.",
    "המעקב אחרי החשבונית נעשה אוטומטית.",
    "שמחנו לשרת אותך.",
]


@pytest.mark.parametrize("cat,text", LEAKS)
def test_hebrew_form_blocked(cat, text):
    assert cat in compliance.violations("סטודיו נועה: " + text, R), text


@pytest.mark.parametrize("text", CLEAN)
def test_ordinary_reminder_wording_not_blocked(text):
    assert compliance.violations("סטודיו נועה: " + text, R) == [], text
