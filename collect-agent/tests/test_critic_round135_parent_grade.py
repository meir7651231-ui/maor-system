"""critic סבב 135 · באג (תבנית מסבב 8): הורה שכותב «הבת שלי בכיתה ח, מתי השיעור הבא?» / «הבן שלי בכיתה ז» ⇒ minor
(השהיה + מייל דחוף) — בעסק של חוגים זו הודעה יומיומית. כלל מנהל 261 ביטל רק כשההורה כתב גם «אשלם/משלמת».
קטין לא כותב «הבת שלי»; הסכנה היא הטלפון/המייל של הילד / ילד שקיבל-ענה — הסימנים האלה עדיין משאירים קטין.
«הבן שלי בכיתה ג» לבד נשאר קטין (הכרעת מנהל 261, test_mgr261) — התיקון רק כשיש שאלה/הקשר של חוג."""
import pytest

from app.conversation import Intent, respond
from evals.harness import build_ctx


def _i(t):
    return respond(t, build_ctx({"channel": "sms"})).intent


@pytest.mark.parametrize("t", ["הבת שלי בכיתה ח, מתי השיעור הבא?", "הבן שלי בכיתה ז, באיזו קבוצה הוא?",
                               "בתי בכיתה ד, אפשר להעביר אותה לקבוצה אחרת?",
                               "הבן שלי בגן, מתי מתחיל החוג?"])
def test_parent_mentions_grade_not_minor(t):
    assert _i(t) != Intent.MINOR, t


@pytest.mark.parametrize("t", [
    "זה הטלפון של הבן שלי, הוא בכיתה ז", "הבת שלי בכיתה ח קיבלה את ההודעה", "הבן שלי בכיתה ג ענה לכם בטעות",
    "אני בכיתה ח", "זה הטלפון של אמא שלי ואני בכיתה ח", "הנייד הזה של הבת שלי בכיתה ו",
    "הבן שלי בכיתה ג",                                   # לבד — הכרעת מנהל 261
    "הבן שלי בן 14 וזה המייל שלו, למה אתם כותבים לו?",
])
def test_child_phone_or_child_writer_still_minor(t):
    assert _i(t) == Intent.MINOR, t
